/**
 * Pushes profile.json into the edit: writes edit/src/profile.json (the brand,
 * sizes and tempo the compositions read) and generates edit/src/fonts.ts for
 * the profile's Google fonts. Run it after every change to the profile:
 *   node lib/apply-profile.mjs
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

import { loadProfile, PROJECT_DIR, rgbTriplet } from "./profile.mjs";

const profile = loadProfile();
const editDir = path.join(PROJECT_DIR, "edit");

function logo() {
  if (!profile.brand.logo) return null;
  const source = path.resolve(PROJECT_DIR, profile.brand.logo);
  if (!existsSync(source)) throw new Error(`brand.logo not found: ${source}`);
  const target = path.join(PROJECT_DIR, "gfx", `logo${path.extname(source)}`);
  mkdirSync(path.dirname(target), { recursive: true });
  if (source !== target) copyFileSync(source, target);
  const [width, height] = execFileSync("ffprobe", [
    "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", target,
  ]).toString().trim().split(",").map(Number);
  return { src: `gfx/${path.basename(target)}`, aspect: height / width };
}

const fontModule = (family) => family.replace(/\s+/g, "");

/** The weights the family really has, out of the ones the edit asks for. */
function weights(family, wanted) {
  try {
    const info = createRequire(path.join(editDir, "package.json"))(`@remotion/google-fonts/${fontModule(family)}`).getInfo();
    const available = Object.keys(info.fonts.normal);
    const usable = wanted.filter((weight) => available.includes(weight));
    return usable.length ? usable : [available.includes("400") ? "400" : available[0]];
  } catch (error) {
    if (error.code === "MODULE_NOT_FOUND" && String(error.message).includes(fontModule(family))) {
      throw new Error(`"${family}" is not a Google Fonts family name the edit can load.`);
    }
    console.warn(`note: could not check weights for ${family} (run npm install in edit/); using the defaults`);
    return wanted;
  }
}

/** Font files from the profile, copied under gfx/fonts so the edit can serve them. */
function ownFiles(family) {
  return (profile.brand.fontFiles ?? []).filter((file) => file.family === family).map((file) => {
    const source = path.resolve(PROJECT_DIR, file.path);
    if (!existsSync(source)) throw new Error(`brand.fontFiles not found: ${source}`);
    const target = path.join(PROJECT_DIR, "gfx", "fonts", path.basename(source));
    mkdirSync(path.dirname(target), { recursive: true });
    if (source !== target) copyFileSync(source, target);
    return { src: `gfx/fonts/${path.basename(source)}`, weight: file.weight };
  });
}

/** The lines of fonts.ts that load one role's font and export its family name. */
function fontSource(role, family, wanted) {
  const files = ownFiles(family);
  if (files.length) {
    const loads = files.map((file) => `void loadFont({ family: ${JSON.stringify(family)}, url: staticFile(${JSON.stringify(file.src)}), weight: ${JSON.stringify(file.weight)} });`);
    return { own: true, lines: [...loads, `export const ${role} = ${JSON.stringify(family)};`] };
  }
  const loader = `load${role[0]}${role.slice(1).toLowerCase()}`;
  return {
    own: false,
    imports: [`import { loadFont as ${loader} } from "@remotion/google-fonts/${fontModule(family)}";`],
    lines: [`export const ${role} = ${loader}("normal", { weights: ${JSON.stringify(weights(family, wanted))}, subsets: ["latin"] }).fontFamily;`],
  };
}

const { heading, body } = profile.brand.fonts;
const fonts = [fontSource("HEADING", heading, ["600", "700"]), fontSource("BODY", body, ["400", "500", "600"])];
const imports = [
  ...(fonts.some((font) => font.own) ? ['import { loadFont } from "@remotion/fonts";', 'import { staticFile } from "remotion";'] : []),
  ...fonts.flatMap((font) => font.imports ?? []),
];
writeFileSync(
  path.join(editDir, "src", "fonts.ts"),
  `// Generated by lib/apply-profile.mjs from profile.json. Do not edit.\n${imports.join("\n")}\n\n${fonts.flatMap((font) => font.lines).join("\n")}\n`,
);

const forEdit = {
  product: profile.product,
  colors: { ...profile.brand.colors, accentRgb: rgbTriplet(profile.brand.colors.accent) },
  logo: logo(),
  bpm: profile.music.bpm,
  phoneScreen: profile.mobile?.screen ?? { width: 1206, height: 2622 },
  webViewport: profile.web?.viewport ?? { width: 1920, height: 1080 },
  stillViewport: profile.web?.stillViewport ?? { width: 1440, height: 900 },
};
writeFileSync(path.join(editDir, "src", "profile.json"), `${JSON.stringify(forEdit, null, 2)}\n`);
console.log(`profile applied: ${profile.organization.name} / ${profile.product.name} (${heading} + ${body}, logo ${forEdit.logo ? forEdit.logo.src : "none"})`);
